def logo_color(key, theme):
    _, light, dark = TECH[key]
    return dark if theme == "dark" and dark else light


# ---------------------------------------------------------------- banner
def banner(lang, theme):
    c, t = COPY[lang], THEMES[theme]
    w, h = WIDTH, 336
    defs = (
        '<defs>'
        f'<pattern id="dots" width="18" height="18" patternUnits="userSpaceOnUse"><circle cx="1.5" cy="1.5" r="1.1" fill="{t["grid"]}"/></pattern>'
        '<linearGradient id="fade" x1="0" x2="1" y1="0" y2="0"><stop offset="0.42" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#fff" stop-opacity="1"/></linearGradient>'
        f'<mask id="fadeMask"><rect width="{w}" height="{h}" fill="url(#fade)"/></mask>'
        f'<clipPath id="cardClip"><rect x="1" y="1" width="{w - 2}" height="{h - 2}" rx="14"/></clipPath>'
        '</defs>'
    )
    body = [defs, rect(0.5, 0.5, w - 1, h - 1, t["header"], t["border"], 14)]
    body.append(f'<g clip-path="url(#cardClip)"><rect width="{w}" height="{h}" fill="url(#dots)" mask="url(#fadeMask)"/></g>')
    # Wordmark A/L/Z.
    body.append(
        f'<text x="48" y="70" font-family="{FONT}" font-size="20" font-weight="700" letter-spacing="1.5" fill="{t["text"]}">'
        f'A<tspan fill="{t["icon"]}">/</tspan>L<tspan fill="{t["icon"]}">/</tspan>Z<tspan fill="{t["green"]}">.</tspan></text>'
    )
    # </> symbol, top right.
    body.append(tile(w - 48 - 44, 40, 44, t, "code-xml", 22))
    # Availability badge.
    label_w = text_width(c["available"], 11.5, 600, 1.2)
    bw = 16 + 10 + 10 + label_w + 16
    body.append(rect(48.5, 108.5, bw - 1, 29, t["raised"], t["border"], 15))
    body.append(f'<circle cx="65" cy="123" r="7" fill="{t["green"]}" opacity="0.18"/><circle cx="65" cy="123" r="4" fill="{t["green"]}"/>')
    body.append(text(80, 127.2, c["available"], 11.5, t["text"], 600, spacing=1.2))
    # Identity.
    body.append(text(46, 200, "Alejandro López Zacarías", 48, t["text"], 700, spacing=-1.2))
    body.append(text(48, 237, c["role"], 21, t["text"], 500, spacing=-0.2))
    body.append(text(48, 267, c["slogan"], 16, t["muted"], 400))
    body.append(f'<line x1="48" y1="290.5" x2="{w - 48}" y2="290.5" stroke="{t["border"]}"/>')
    body.append(icon("map-pin", 47, 302, 16, t["muted"], 2))
    body.append(text(70, 315, c["location"], 14, t["muted"], 500))
    body.append(text(w - 48, 315, "github.com/A-L-Z", 13, t["icon"], 400, anchor="end", family=MONO))
    title = f"Alejandro López Zacarías — {c['role']}"
    desc = f"{c['available']}. {c['slogan']} {c['location']}."
    return svg(w, h, "".join(body), title, desc)


# ---------------------------------------------------------------- language toggle
def lang_toggle(theme):
    """Summary button of the collapsible Spanish version (stays on the profile page)."""
    t = THEMES[theme]
    label = "Ver en español"
    h = 36
    w = round(12 + 18 + 10 + text_width("ES", 13, 700, 0.6) + 10 + text_width(label, 14, 500) + 14)
    body = (frame(0, 0, w, h, t, "card", 10) + icon("globe", 12, 9, 18, t["text"], 1.9)
            + text(40, 23, "ES", 13, t["text"], 700, spacing=0.6)
            + f'<line x1="{40 + text_width("ES", 13, 700, 0.6) + 5:.1f}" y1="11" x2="{40 + text_width("ES", 13, 700, 0.6) + 5:.1f}" y2="25" stroke="{t["border"]}"/>'
            + text(40 + text_width("ES", 13, 700, 0.6) + 10, 23, label, 14, t["muted"], 500))
    return svg(w, h, body, "ES — Ver en español")


# ---------------------------------------------------------------- small chips
def chip(icon_name, label, theme, logo=None, logo_color_=None):
    t = THEMES[theme]
    h, size = 36, 14
    tw = text_width(label, size, 500)
    w = round(12 + 18 + 9 + tw + 14)
    body = [frame(0, 0, w, h, t, "card", 10)]
    if logo:
        body.append(brand(logo, 12, 9, 18, logo_color_))
    else:
        body.append(icon(icon_name, 12, 9, 18, t["text"] if icon_name != "braces" else t["muted"], 1.9))
    body.append(text(39, 23, label, size, t["text"], 500))
    return svg(w, h, "".join(body), label)


def category_label(label, theme):
    t = THEMES[theme]
    w, h = 132, 36
    return svg(w, h, text(2, 23, label.upper(), 11.5, t["muted"], 600, spacing=1.3), label)


# ---------------------------------------------------------------- expertise grid
def expertise(lang, theme):
    c, t = COPY[lang], THEMES[theme]
    gap, cw, ch = 16, (WIDTH - 16) / 2, 148
    body = []
    for i, (ic, title, desc) in enumerate(c["expertise"]):
        x, y = (i % 2) * (cw + gap), (i // 2) * (ch + gap)
        body.append(frame(x, y, cw, ch, t, "card", 12))
        body.append(tile(x + 24, y + 24, 44, t, ic, 22))
        body.append(text(x + 24, y + 100, title, 18, t["text"], 600, spacing=-0.2))
        body.append(text(x + 24, y + 125, desc, 15, t["muted"], 400))
    h = ch * 2 + gap
    summary = "; ".join(f"{a}: {b}" for _, a, b in c["expertise"])
    return svg(WIDTH, h, "".join(body), c["expertise_title"], summary)


# ---------------------------------------------------------------- project cards
def project(lang, theme, data):
    c, t = COPY[lang], THEMES[theme]
    _, ic, name, subtitle, description, tags = data
    w, pad = WIDTH, 32
    lines = wrap(description, 16, 400, w - pad * 2)
    desc_y = 124
    divider_y = desc_y + (len(lines) - 1) * 24 + 30
    tags_y = divider_y + 20
    h = tags_y + 30 + pad - 4
    body = [frame(0, 0, w, h, t, "card", 14)]
    body.append(tile(pad, pad, 52, t, ic, 24))
    body.append(text(pad + 72, pad + 22, name, 23, t["text"], 700, spacing=-0.4))
    body.append(text(pad + 72, pad + 47, subtitle, 15.5, t["muted"], 500))
    badge, bw = pill(0, 0, c["private"], t, 12.5, 500, "lock", 28)
    body.append(f'<g transform="translate({w - pad - bw:g} {pad + 4})">{badge}</g>')
    for i, line in enumerate(lines):
        body.append(text(pad, desc_y + i * 24, line, 16, t["text"], 400))
    body.append(f'<line x1="{pad}" y1="{divider_y + .5}" x2="{w - pad}" y2="{divider_y + .5}" stroke="{t["border"]}"/>')
    x = pad
    for logo, label in tags:
        size, tw = 13, text_width(label, 13, 500)
        tag_w = (12 + 15 + 7 if logo else 12) + tw + 12
        body.append(rect(x + .5, tags_y + .5, tag_w - 1, 29, t["raised"], t["border"], 8))
        tx = x + 12
        if logo:
            body.append(brand(logo, tx, tags_y + 7.5, 15, logo_color(logo, theme)))
            tx += 22
        body.append(text(tx, tags_y + 19.5, label, size, t["muted"], 500))
        x += tag_w + 8
    tech = ", ".join(label for _, label in tags)
    return svg(w, h, "".join(body), f"{name} — {subtitle}", f"{c['private']}. {description} {tech}.")


def explore(lang, theme):
    c, t = COPY[lang], THEMES[theme]
    w, h = WIDTH, 56
    tw = text_width(c["explore"], 15, 600)
    total = tw + 8 + 16
    x0 = (w - total) / 2
    body = (frame(0, 0, w, h, t, "card", 12)
            + text(x0, 33, c["explore"], 15, t["text"], 600)
            + icon("arrow-up-right", x0 + tw + 8, 20, 16, t["text"], 2.2))
    return svg(w, h, body, c["explore"] + " ↗")


# ---------------------------------------------------------------- languages
def languages(lang, theme):
    c, t = COPY[lang], THEMES[theme]
    w, row = WIDTH, 80
    h = row * len(c["languages"])
    body = [frame(0, 0, w, h, t, "card", 12)]
    for i, (code, name, items) in enumerate(c["languages"]):
        y = i * row
        if i:
            body.append(f'<line x1="24" y1="{y + .5}" x2="{w - 24}" y2="{y + .5}" stroke="{t["border"]}"/>')
        body.append(rect(24.5, y + 18.5, 43, 43, t["raised"], t["border"], 10))
        body.append(text(46, y + 45, code, 14, t["text"], 700, anchor="middle", spacing=0.6))
        body.append(text(86, y + 46, name, 17, t["text"], 600))
        x = w - 24
        for ic, label in reversed(items):
            p, pw = pill(0, 0, label, t, 13, 500, ic, 30)
            x -= pw
            body.append(f'<g transform="translate({x:g} {y + 25})">{p}</g>')
            x -= 8
    summary = "; ".join(f"{n}: {', '.join(l for _, l in it)}" for _, n, it in c["languages"])
    return svg(w, h, "".join(body), summary)


# ---------------------------------------------------------------- availability card
def availability(lang, theme):
    c, t = COPY[lang], THEMES[theme]
    w, pad = WIDTH, 40
    body = []
    # Items flow into rows.
    items, x, y = [], pad, 150
    for label in c["cta_items"]:
        p, pw = pill(0, 0, label, t, 13.5, 500, "check", 34, color=t["text"])
        if x + pw > w - pad:
            x, y = pad, y + 44
        items.append(f'<g transform="translate({x:g} {y})">{p}</g>')
        x += pw + 10
    button_y = y + 34 + 32
    h = button_y + 44 + pad
    body.append(frame(0, 0, w, h, t, "card", 14))
    body.append(f'<circle cx="{pad + 5}" cy="{pad + 6}" r="4" fill="{t["green"]}"/>')
    body.append(text(pad + 18, pad + 10.5, COPY[lang]["available"], 11.5, t["muted"], 600, spacing=1.2))
    body.append(text(pad - 1, pad + 52, c["cta_title"], 30, t["text"], 700, spacing=-0.7))
    body.append(text(pad, pad + 82, c["cta_text"], 16, t["muted"], 400))
    body.extend(items)
    bt = text_width(c["cta_button"], 14, 600)
    bw = 16 + 18 + 10 + bt + 6 + 14 + 16
    fill, ink = (t["text"], t["page"])
    body.append(rect(pad, button_y, bw, 44, fill, None, 10))
    body.append(brand("github", pad + 16, button_y + 13, 18, ink))
    body.append(text(pad + 44, button_y + 27, c["cta_button"], 14, ink, 600))
    body.append(icon("arrow-up-right", pad + 44 + bt + 6, button_y + 15, 14, ink, 2.4))
    return svg(w, h, "".join(body), c["cta_title"], f"{c['cta_text']} {', '.join(c['cta_items'])}.")


# ---------------------------------------------------------------- build
def main():
    for theme in THEMES:
        write(f"buttons/lang-toggle-es-{theme}.svg", lang_toggle(theme))
        for key in TECH:
            label = TECH[key][0]
            if key == "rest":
                for lang in COPY:
                    write(f"cards/stack/rest-{lang}-{theme}.svg", chip("braces", COPY[lang]["rest"], theme))
                continue
            write(f"cards/stack/{key}-{theme}.svg", chip(None, label, theme, key, logo_color(key, theme)))
        for lang, c in COPY.items():
            write(f"banners/banner-{lang}-{theme}.svg", banner(lang, theme))
            for ic, label, slug in c["chips"]:
                write(f"cards/chip-{slug}-{lang}-{theme}.svg", chip(ic, label, theme))
            for cat, label in c["categories"].items():
                write(f"cards/stack/label-{cat}-{lang}-{theme}.svg", category_label(label, theme))
            write(f"cards/expertise-{lang}-{theme}.svg", expertise(lang, theme))
            for data in c["projects"]:
                write(f"cards/project-{data[0]}-{lang}-{theme}.svg", project(lang, theme, data))
            write(f"buttons/explore-{lang}-{theme}.svg", explore(lang, theme))
            write(f"cards/languages-{lang}-{theme}.svg", languages(lang, theme))
            write(f"cards/availability-{lang}-{theme}.svg", availability(lang, theme))
    print("Static assets generated.")


if __name__ == "__main__":
    main()
